// Generates src/data/comparison-sections.ts
// Per-pair "分场景推荐" sections for comparison pages. Every value cited here is
// taken from the real catalog (src/data/catalog/browsers.json) merged with the
// detailedBrowsers overrides in src/data/resources.ts — nothing is invented.
// Sentences are emitted conditionally (only when the two browsers differ on that
// dimension) so each comparison page reads differently and stays factual.

import { readFileSync, writeFileSync } from "node:fs";

const browsersJson = JSON.parse(readFileSync(new URL("../src/data/catalog/browsers.json", import.meta.url), "utf8"));
const readmeJson = JSON.parse(readFileSync(new URL("../src/data/catalog/readme-browsers.json", import.meta.url), "utf8"));

// Displayed free/price overrides (exact strings from detailedBrowsers in resources.ts).
const detailed = {
  easybr: { free: "5 个环境终身免费", price: "$3+/month" },
  gologin: { free: "3 个浏览器档案", price: "$9/月起（Professional；当前促销 $4.50/月）" },
  adspower: { free: "2 个档案永久免费", price: "$9/月起（Professional；年付折算 $7.20/月）" },
  multilogin: { free: "5 个档案免费", price: "$7.08/月起（年付）" },
  "dolphin-anty": { free: "5 个档案免费", price: "$10/月起" },
  morelogin: { free: "2 个档案永久免费", price: "$5.40/月起" },
  incogniton: { free: "前 2 个月 10 个档案，之后 3 个", price: "$19.99/月起（半年计费）" },
  bitbrowser: { free: "10 个档案永久免费", price: "$10/月起（50 个档案）" },
  "octo-browser": { free: "试用/促销额度以官网为准", price: "$10/月起" },
  kameleo: { free: "免费计划；100 个云端档案", price: "$51.93/月起（约 €45）" },
  undetectable: { free: "5–45 个云端档案免费", price: "$34/月起" }
};

const catalogById = new Map(browsersJson.browsers.map(b => [b.id, b]));
const readmeById = new Map(readmeJson.browsers.map(b => [b.id, b]));

function display(id) {
  const cat = catalogById.get(id);
  const rd = readmeById.get(id);
  const d = detailed[id] ?? {};
  return {
    id,
    name: cat?.name ?? rd?.name ?? id,
    free: d.free ?? rd?.freePlan ?? "以官网为准",
    price: d.price ?? rd?.price ?? "以官网为准",
    platforms: (cat?.platforms ?? rd?.platforms ?? []).map(p => p.replace("windows", "Windows").replace("macos", "macOS").replace("linux", "Linux").replace("cloud", "Cloud").replace("android", "Android").replace("desktop", "Desktop").replace("server", "Server")),
    engine: cat?.engine ?? "以官网为准",
    storage: cat?.storage ?? "以官网为准",
    bestFor: cat?.bestFor ?? []
  };
}

const comparisons = [
  ["easybr", "adspower"], ["easybr", "gologin"], ["easybr", "multilogin"], ["easybr", "dolphin-anty"],
  ["easybr", "morelogin"], ["easybr", "bitbrowser"], ["adspower", "gologin"], ["adspower", "multilogin"],
  ["gologin", "multilogin"], ["dolphin-anty", "morelogin"], ["bitbrowser", "adspower"], ["incogniton", "gologin"],
  ["morelogin", "multilogin"], ["adspower", "dolphin-anty"], ["adspower", "morelogin"], ["adspower", "incogniton"],
  ["gologin", "dolphin-anty"], ["gologin", "morelogin"], ["gologin", "incogniton"], ["gologin", "kameleo"],
  ["gologin", "octo-browser"],   ["multilogin", "dolphin-anty"], ["multilogin", "incogniton"], ["multilogin", "kameleo"],
  ["dolphin-anty", "incogniton"], ["morelogin", "bitbrowser"], ["octo-browser", "undetectable"],
  ["kameleo", "octo-browser"], ["undetectable", "gologin"]
];

function scenario(a, b) {
  const parts = [];
  parts.push(`若免费额度是首要约束：${a.name} 当前为「${a.free}」，${b.name} 为「${b.free}」。免费计划的可用环境数与保留规则会随官网调整，开始工作流前以各自官网当前页面为准。`);
  parts.push(`若按价格起步比较：${a.name} 起步约 ${a.price}，${b.name} 起步约 ${b.price}。多账号场景里代理流量常单独计费，核算成本时要把代理费用与档案数量一并计入。`);
  if (a.platforms.join() !== b.platforms.join()) {
    parts.push(`平台覆盖不同：${a.name} 支持 ${a.platforms.join("、")}，${b.name} 支持 ${b.platforms.join("、")}。需要 Linux 或服务端批量运行时，先确认目标工具是否覆盖你的工作环境。`);
  }
  if (a.storage !== b.storage) {
    parts.push(`存储方式不同：${a.name} 为 ${a.storage}，${b.name} 为 ${b.storage}。本地优先更利于离线使用与数据自主管控，云端更便于跨设备协作，选择取决于你对数据位置与备份的要求。`);
  }
  if (a.engine !== b.engine) {
    parts.push(`浏览器内核不同：${a.name} 基于 ${a.engine}，${b.name} 基于 ${b.engine}。内核决定了指纹信号的基线，选型时应确认厂商的内核跟进与更新节奏。`);
  }
  parts.push(`适用场景侧重：${a.name} 更偏向 ${a.bestFor.join("、")}；${b.name} 更偏向 ${b.bestFor.join("、")}。把它作为核对清单，再结合你实际的账号数量、协作规模和合规要求做决定。`);
  return parts.join("\n\n");
}

const entries = comparisons.map(([aId, bId]) => {
  const a = display(aId);
  const b = display(bId);
  const slug = `${aId}-vs-${bId}`;
  return `  "${slug}": [\n    { heading: "分场景推荐", body: ${JSON.stringify(scenario(a, b))} }\n  ]`;
}).join(",\n");

const out = `// AUTO-GENERATED by scripts/gen-comparison-sections.mjs — do not edit by hand.
// Per-pair "分场景推荐" sections for comparison pages. Values are cited from the
// real catalog (src/data/catalog/browsers.json) merged with the detailedBrowsers
// overrides in src/data/resources.ts. Nothing here is fabricated.

export type ComparisonSection = { heading: string; body: string };

export const comparisonSections: Record<string, ComparisonSection[]> = {
${entries}
};
`;

writeFileSync(new URL("../src/data/comparison-sections.ts", import.meta.url), out);
console.log(`Wrote comparison-sections.ts with ${comparisons.length} comparisons.`);
