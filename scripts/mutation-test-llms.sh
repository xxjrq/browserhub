#!/usr/bin/env bash
# Mutation test for scripts/check-llms-txt.mjs.
#
# A validation script that only ever passes is worthless. This harness injects
# a defect into the llms.txt route, rebuilds the affected artefact and asserts
# that the checker reports the defect BY NAME rather than crashing or passing.
#
# Each mutation prints `applied: true/false`. A mutation that did not apply
# proves nothing, so the harness fails loudly in that case too.
#
# Mutations:
#   1. Drop the comparison section entirely       -> "section" failure
#   2. Point one comparison link at a bogus URL    -> "resolves to a built page"
#   3. Leak Chinese into an English description    -> "contains no CJK"
#   4. Remove the review date from a product line  -> "review date"
#
# The route file is restored afterwards, and the working tree is checked so a
# failed run cannot leave a mutated source behind.

set -uo pipefail

cd "$(dirname "$0")/.."
ROUTE="src/app/llms.txt/route.ts"
BACKUP="$(mktemp -t llms-route-backup.XXXXXX.ts)"
cp "$ROUTE" "$BACKUP"

restore() {
	cp "$BACKUP" "$ROUTE"
	rm -f "$BACKUP"
}
trap restore EXIT

PASS=0
FAIL=0

run_mutation() {
	local name="$1"
	local pattern="$2"
	local replacement="$3"
	local expect="$4"

	echo "=== mutation: $name ==="
	# Confirm the mutation text is actually present before editing.
	if ! grep -qF -- "$pattern" "$ROUTE"; then
		echo "  applied: false — pattern not found in $ROUTE"
		echo "  RESULT: FAIL (mutation never applied, so the test proves nothing)"
		FAIL=$((FAIL + 1))
		return
	fi

	python3 - "$ROUTE" "$pattern" "$replacement" <<'PY'
import sys
path, pattern, replacement = sys.argv[1], sys.argv[2], sys.argv[3]
with open(path, encoding="utf8") as fh:
	text = fh.read()
with open(path, "w", encoding="utf8") as fh:
	fh.write(text.replace(pattern, replacement, 1))
PY

	echo "  applied: true"

	# Rebuild only what the route produces. The route is a static route, so the
	# rendered file is regenerated by the check script itself; the build output
	# comparison (check 7) is expected to fail for every mutation, which is
	# fine as long as the specific expected defect is also reported.
	local output
	output="$(node scripts/check-llms-txt.mjs 2>&1)"

	if echo "$output" | grep -qF -- "$expect"; then
		echo "  RESULT: PASS — reported \"$expect\""
		PASS=$((PASS + 1))
	else
		echo "  RESULT: FAIL — expected \"$expect\" was not reported"
		echo "$output" | head -8 | sed 's/^/    /'
		FAIL=$((FAIL + 1))
	fi

	# Restore before the next mutation, so each one is tested in isolation
	# rather than on top of the previous defect.
	cp "$BACKUP" "$ROUTE"
	echo
}

run_mutation \
	"comparison section removed" \
	"const compareFacts = comparisons.map(comparisonLine).join(\"\\n\");" \
	"const compareFacts = \"\";" \
	'section "Browser comparisons"'

run_mutation \
	"comparison link points at a URL that does not exist" \
	'`/zh-cn/compare/${c.slug}/`, c.title)}' \
	'`/zh-cn/compare/${c.slug}-does-not-exist/`, c.title)}' \
	"resolves to a built page"

run_mutation \
	"Chinese leaks into an English description" \
	'localizedResourceDescription("en", "tools", t)}' \
	'"中文泄漏 " + localizedResourceDescription("en", "tools", t)}' \
	"contains no CJK"

run_mutation \
	"review date removed from a product line" \
	'Public documentation reviewed ${evidence.verifiedAt}; pricing status:' \
	'Public documentation reviewed; pricing status:' \
	"review date"

restore
trap - EXIT

# The source must be byte-identical to the backup after the run.
if ! git diff --quiet -- "$ROUTE" 2>/dev/null; then
	echo "WARNING: $ROUTE differs from HEAD after the mutation run (expected: the route was intentionally changed this session)."
fi

echo "=== mutation summary: $PASS passed, $FAIL failed ==="
[ "$FAIL" -eq 0 ]
